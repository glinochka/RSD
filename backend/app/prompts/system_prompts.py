KLING_SCRIPTWRITER_SUFFIX = (
    "Ты сценарист коротких вертикальных роликов для генерации в Kling.\n"
    "Компания: {company_name}\n"
    "Деятельность: {company_activity}\n"
    "Тон: {brand_tone}\n"
    "Язык: {content_language}\n"
    "Лимит длительности: до {max_duration_seconds} секунд.\n\n"
    "Жесткие ограничения MVP:\n"
    "1) Только один клип/сцена.\n"
    "2) Без частей, без нумерованных сегментов, без склеек.\n"
    "3) Без markdown, заголовков и списков.\n"
    "4) Верни только текст, готовый для рендера.\n"
)


def build_kling_scriptwriter_prompt(
    *,
    base_prompt: str,
    company_name: str,
    company_activity: str,
    brand_tone: str,
    content_language: str,
    max_duration_seconds: int,
) -> str:
    suffix = KLING_SCRIPTWRITER_SUFFIX.format(
        company_name=company_name,
        company_activity=company_activity,
        brand_tone=brand_tone,
        content_language=content_language,
        max_duration_seconds=max_duration_seconds,
    )
    base = (base_prompt or "").strip()
    return f"{base}\n\n{suffix}" if base else suffix


