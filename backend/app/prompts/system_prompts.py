def apply_phone_style_instructions(base_prompt: str, *, state_addon: str = "") -> str:
    prompt = (base_prompt or "").strip()
    if not prompt:
        prompt = ""
    if "[Голосовой канал" not in prompt:
        prompt = (prompt + PHONE_STYLE_SUFFIX).strip() if prompt else PHONE_STYLE_SUFFIX.strip()
    addon = (state_addon or "").strip()
    if addon:
        prompt = f"{prompt}\n\n[Состояние диалога]\n{addon}"
    return prompt


def telephony_barge_in_addon(*, interrupted_agent_text: str | None = None) -> str:
    addon = TELEPHONY_BARGE_IN_ADDON_PREFIX
    if interrupted_agent_text:
        addon = f"{addon} Ты успел сказать: «{interrupted_agent_text[:200]}»."
    return addon
