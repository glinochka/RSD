def build_crm_admin_system_prompt(
    *,
    agent_prompt: str,
    context_tail: str,
    today_date: str,
    portrait_block: str = "",
    knowledge_catalog_block: str = "",
) -> str:
    today_year = today_date[:4] if len(today_date) >= 4 else ""
    core = CRM_ADMIN_CORE_INSTRUCTION.format(
        today_date=today_date,
        today_year=today_year or "текущий",
        context_tail=context_tail.strip(),
    )
    system_prompt = f"{agent_prompt.strip()}\n\n{core}".strip()
    catalog = (knowledge_catalog_block or "").strip()
    if catalog:
        system_prompt = f"{system_prompt}\n\n{catalog}"
    if portrait_block:
        system_prompt = f"{system_prompt}\n\n{portrait_block}"
    return system_prompt


