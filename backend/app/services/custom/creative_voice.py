TONE_LINES = {
    "expert_friendly": "Говорит как свой из ниши: точно, без лекции и без улыбки ведущего.",
    "bold": "Жёстко и коротко. Злость уместна. Мат — если без него фраза становится рекламной.",
    "calm": "Сухо и конкретно. Юмор только если сам вылез из факта, не вставляй шутку силой.",
    "sales": "Продажа через наблюдение о новости. Оффер не в первом кадре и не вместо мысли.",
    "satire": "Одна злая насмешка над событием. Не пародия на стендап и не объяснение шутки.",
}


def tone_line(tone: str | None) -> str:
    key = str(tone or "").strip()
    return TONE_LINES.get(key) or TONE_LINES["expert_friendly"]
